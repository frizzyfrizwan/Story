/** Returns the guide for the given week, clamped to the 1–42 range. */
export function getWeekGuide(week: number): WeekGuide {
  const safe = Number.isFinite(week) ? Math.round(week) : 1
  const clamped = Math.min(42, Math.max(1, safe))
  return WEEKS[clamped - 1]
}
