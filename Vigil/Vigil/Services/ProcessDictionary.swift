import Foundation

/// Plain-English explanations for the macOS processes people actually ask about.
struct ProcessExplanation: Equatable {
    enum Verdict: Equatable {
        case system          // part of macOS, leave it alone
        case safeToQuit      // an app or helper you can quit
        case investigate     // normal in bursts, suspicious when sustained
    }

    let title: String
    let summary: String
    let verdict: Verdict
    let category: String
}

enum ProcessDictionary {
    static func explanation(for name: String, bundleIdentifier: String? = nil, isApplication: Bool = false) -> ProcessExplanation {
        let key = name.lowercased()
        if let exact = entries[key] { return exact }
        for (prefix, entry) in prefixEntries where key.hasPrefix(prefix) { return entry }
        if let bundle = bundleIdentifier?.lowercased() {
            if bundle.contains("webkit.webcontent") { return entries["com.apple.webkit.webcontent"]! }
            if bundle.hasPrefix("com.apple.") { return ProcessExplanation(title: name, summary: "Part of macOS or an Apple app.", verdict: .system, category: "macOS") }
        }
        if isApplication {
            return ProcessExplanation(title: name, summary: "An app you (or a login item) opened. Quitting it is safe; unsaved work will prompt first.", verdict: .safeToQuit, category: "App")
        }
        if key.hasSuffix("d") && !key.contains(" ") {
            return ProcessExplanation(title: name, summary: "A background daemon. The trailing \"d\" is a Unix convention for services that run without a window.", verdict: .investigate, category: "Background")
        }
        return ProcessExplanation(title: name, summary: "A background helper. If it stays busy for minutes, check which app installed it.", verdict: .investigate, category: "Background")
    }

    private static func sys(_ title: String, _ summary: String, _ category: String = "macOS") -> ProcessExplanation {
        ProcessExplanation(title: title, summary: summary, verdict: .system, category: category)
    }
    private static func inv(_ title: String, _ summary: String, _ category: String = "macOS") -> ProcessExplanation {
        ProcessExplanation(title: title, summary: summary, verdict: .investigate, category: category)
    }
    private static func app(_ title: String, _ summary: String, _ category: String = "App") -> ProcessExplanation {
        ProcessExplanation(title: title, summary: summary, verdict: .safeToQuit, category: category)
