export const ROUTES: RouteDef[] = ROWS.flatMap(
  ([origin, destination, carrier, aircraft, outMin, backMin, weeklyFrequency, cabins, outFlight, backFlight]) => {
    const types = aircraft.split(" ");
    const cabinList = cabins.split("").map((c) => CABIN_OF[c]);
    const out: RouteDef = { origin, destination, carrier, aircraft: types, durationMin: outMin, weeklyFrequency, cabins: cabinList };
    const back: RouteDef = { origin: destination, destination: origin, carrier, aircraft: types, durationMin: backMin, weeklyFrequency, cabins: cabinList };
    if (outFlight) out.flightNumber = outFlight;
    if (backFlight) back.flightNumber = backFlight;
    return [out, back];
  },
);

/** Total directional RouteDef entries (each city pair contributes two). */
export const ROUTE_COUNT = ROUTES.length;

export function routesFrom(origin: string): RouteDef[] {
  const o = origin.toUpperCase();
  return ROUTES.filter((r) => r.origin === o);
}

/** Routes in either direction between two airports. */
export function routesBetween(origin: string, destination: string): RouteDef[] {
  const o = origin.toUpperCase();
  const d = destination.toUpperCase();
  return ROUTES.filter((r) => (r.origin === o && r.destination === d) || (r.origin === d && r.destination === o));
}

/** Distinct destination codes reachable nonstop from an origin. */
export function destinationsFrom(origin: string): string[] {
  return Array.from(new Set(routesFrom(origin).map((r) => r.destination)));
}

/** Distinct carriers (IATA) flying nonstop between two airports, in either direction. */
export function carriersOn(origin: string, destination: string): string[] {
  return Array.from(new Set(routesBetween(origin, destination).map((r) => r.carrier)));
}

